alter table public.tren_rodaje enable row level security;
alter table public.tren_rodaje_mediciones enable row level security;
alter table public.historial_componentes enable row level security;
alter table public.historial_neumaticos enable row level security;

do $$
declare t text;
begin
  foreach t in array array['tren_rodaje','tren_rodaje_mediciones','historial_componentes','historial_neumaticos']
  loop
    if not exists (select 1 from pg_policies where schemaname='public' and tablename=t and policyname='operacional_select') then
      execute format('create policy "operacional_select" on public.%I for select to authenticated using (privado.es_usuario_activo())', t);
    end if;
    if not exists (select 1 from pg_policies where schemaname='public' and tablename=t and policyname='operacional_insert') then
      execute format('create policy "operacional_insert" on public.%I for insert to authenticated with check (privado.es_editor_activo())', t);
    end if;
    if not exists (select 1 from pg_policies where schemaname='public' and tablename=t and policyname='operacional_update') then
      execute format('create policy "operacional_update" on public.%I for update to authenticated using (privado.es_editor_activo()) with check (privado.es_editor_activo())', t);
    end if;
    if not exists (select 1 from pg_policies where schemaname='public' and tablename=t and policyname='operacional_delete') then
      execute format('create policy "operacional_delete" on public.%I for delete to authenticated using (privado.es_editor_activo())', t);
    end if;
  end loop;
end $$;

