-- Encontrado al investigar si el respaldo diario (backup-diario) es
-- realmente restaurable: 8 de las 49 tablas que ese respaldo SÍ junta nunca
-- tuvieron un CREATE TABLE en ninguna migración — se crearon a mano en el
-- dashboard de Supabase en algún momento. Sin esto, ni siquiera se podría
-- reconstruir el ESQUEMA completo desde cero a partir del repo — un
-- requisito básico para que el respaldo sirva ante la pérdida TOTAL de un
-- proyecto Supabase (no solo corrupción de datos, donde alcanza con
-- restaurar filas sobre un esquema que ya existe).
--
-- Esquema copiado 1:1 del proyecto real (introspección read-only,
-- 2026-09-11). `if not exists` en todo: estas 8 tablas YA EXISTEN en los
-- proyectos reales (Besalco y sistema-mp2) — ahí esta migración es un
-- no-op total; solo importa para poder reproducir el esquema completo en
-- un proyecto nuevo desde cero.

-- user_roles: la tabla de autorización central (rol/activo de cada login).
create table if not exists public.user_roles (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid,
  role text,
  nombre text,
  activo boolean not null default true
);
alter table public.user_roles enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='user_roles' and policyname='usuarios ven su propio rol') then
    create policy "usuarios ven su propio rol" on public.user_roles for select to authenticated using ((select auth.uid()) = user_id);
  end if;
end $$;

-- Tablas operacionales (tren de rodaje, historiales de repuesto).
create table if not exists public.tren_rodaje (
  id text primary key default (gen_random_uuid())::text,
  sigla text not null,
  lado text not null,
  componente text not null,
  "valorNuevo" numeric,
  "limiteDesgaste" numeric,
  "valorActual" numeric,
  "pctRemanente" numeric,
  "fechaInst" date,
  "ultimaMedicion" date,
  "horomInstalacion" numeric,
  estado text default 'Operativo',
