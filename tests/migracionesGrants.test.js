import { describe, it, expect } from 'vitest';
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { revisarMigracion, revisarCarpeta, GRANTS_DESDE } = require('../scripts/revisar-grants-migraciones.js');

// Desde el 30-oct-2026 Supabase no da permisos automáticos a lo que se crea en `public`: cada migración nueva debe traer sus GRANT.
describe('revisarMigracion: detecta lo que se creó sin permisos', () => {
  it('tabla sin GRANT: falla para authenticated y service_role', () => {
    const p = revisarMigracion('create table public.nueva (id text primary key);\nalter table public.nueva enable row level security;');
    expect(p).toContain('la tabla public.nueva no tiene GRANT para authenticated');
    expect(p).toContain('la tabla public.nueva no tiene GRANT para service_role');
  });
  it('tabla con sus GRANT (mayúsculas, "on table", esquema explícito): bien', () => {
    const sql = `CREATE TABLE IF NOT EXISTS public.nueva (id text);
      GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.nueva TO authenticated;
      grant select, insert, update, delete on public.nueva to service_role;`;
    expect(revisarMigracion(sql)).toEqual([]);
  });
  it('un GRANT solo para anon no alcanza', () => {
    expect(revisarMigracion('create table public.x (id int);\ngrant select on public.x to anon;')).toHaveLength(2);
  });
  it('un GRANT de otra tabla con nombre parecido no cuenta', () => {
    const sql = 'create table public.pedido (id int);\ngrant select, insert on public.pedido_detalle to authenticated, service_role;';
    expect(revisarMigracion(sql)).toHaveLength(2);
  });
  it('lo que aparece solo en comentarios no cuenta', () => {
    const sql = 'create table public.x (id int);\n-- grant select on public.x to authenticated, service_role;\n/* grant all on public.x to service_role */';
    expect(revisarMigracion(sql)).toHaveLength(2);
  });
  it('un GRANT que nombra varias tablas a la vez sirve para cada una', () => {
    const sql = 'create table public.a (id int);\ncreate table public.b (id int);\ngrant select, insert, update, delete on public.a, public.b to authenticated, service_role;';
    expect(revisarMigracion(sql)).toEqual([]);
  });
  it('tablas de otros esquemas (privado, auth) no se exigen', () => {
    expect(revisarMigracion('create table privado.cache (id int);')).toEqual([]);
  });
  it('función normal sin EXECUTE: falla; de trigger: no se exige; con EXECUTE: bien', () => {
    expect(revisarMigracion('create or replace function public.calcula(x int) returns int language sql as $$ select x $$;')).toContain('la función public.calcula no tiene GRANT EXECUTE');
    expect(revisarMigracion('create or replace function public.actualiza() returns trigger language plpgsql as $$ begin return new; end $$;')).toEqual([]);
    expect(revisarMigracion('create function public.calcula(x int) returns int language sql as $$ select x $$;\ngrant execute on function public.calcula(int) to authenticated;')).toEqual([]);
  });
  it('columna identity/serial sin GRANT sobre la secuencia: falla', () => {
    const base = 'create table public.t (id bigint generated by default as identity primary key);\ngrant select, insert, update, delete on public.t to authenticated, service_role;';
    expect(revisarMigracion(base)).toEqual(['hay una columna serial/identity pero no hay GRANT USAGE sobre su secuencia']);
    expect(revisarMigracion(base + '\ngrant usage, select on sequence public.t_id_seq to service_role;')).toEqual([]);
  });
});

describe('migraciones del repositorio', () => {
  const dir = path.resolve(__dirname, '../supabase/migrations');
  it('existe la migración que da permisos explícitos a todo lo anterior', () => {
    const f = fs.readdirSync(dir).find((n) => n.startsWith(GRANTS_DESDE));
    expect(f).toBeTruthy();
    const sql = fs.readFileSync(path.join(dir, f), 'utf8');
    expect(sql).toMatch(/grant select, insert, update, delete on table public\.%I to authenticated/);
    expect(sql).toMatch(/to service_role/);
    expect(sql).not.toMatch(/to\s+anon/i);                              // anon no recibe nada: la app exige sesión
    expect(sql).toMatch(/revoke update, delete, truncate on public\.auditoria_cambios from authenticated/);   // bitácora de solo agregar
  });
  it('ninguna migración posterior crea tablas, funciones o secuencias sin sus GRANT', () => {
    expect(revisarCarpeta(dir)).toEqual([]);
  });
});
